#!/usr/bin/env python3
"""Generate every secret the stack needs, once, into secrets/secrets.yml (gitignored).

Re-running is a no-op unless --force is given. Keys are X25519 for both WireGuard/AmneziaWG
(standard base64) and Xray Reality (base64url without padding), which is exactly what
`awg genkey` and `xray x25519` would produce.
"""
import argparse
import base64
import os
import secrets
import sys
import uuid
from pathlib import Path

import yaml
from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric.x25519 import X25519PrivateKey

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "secrets" / "secrets.yml"
VARS = ROOT / "ansible" / "group_vars" / "all" / "main.yml"


def x25519_pair():
    priv = X25519PrivateKey.generate()
    raw_priv = priv.private_bytes(serialization.Encoding.Raw, serialization.PrivateFormat.Raw,
                                  serialization.NoEncryption())
    raw_pub = priv.public_key().public_bytes(serialization.Encoding.Raw, serialization.PublicFormat.Raw)
    return raw_priv, raw_pub


def wg_pair():
    p, q = x25519_pair()
    return base64.b64encode(p).decode(), base64.b64encode(q).decode()


def wg_psk():
    return base64.b64encode(secrets.token_bytes(32)).decode()


def reality_pair():
    p, q = x25519_pair()
    b64u = lambda b: base64.urlsafe_b64encode(b).decode().rstrip("=")
    return b64u(p), b64u(q)


def awg_params():
    """AmneziaWG obfuscation set understood by KeeneticOS 5.1, AmneziaWG app 3.x and the 3.x kernel module.
    Rules: S1 + 56 != S2; H1..H4 distinct, >= 5. I1 is a QUIC-Initial-shaped signature packet (1.5+ syntax)."""
    while True:
        s1, s2 = secrets.randbelow(136) + 15, secrets.randbelow(136) + 15
        if s1 + 56 != s2:
            break
    hs = set()
    while len(hs) < 4:
        hs.add(secrets.randbelow(2_000_000_000) + 5)
    h1, h2, h3, h4 = sorted(hs)
    # c3 = QUIC long header/Initial with 4-byte packet number, version 1, DCID len 8, SCID len 0,
    # token len 0, length varint 0x43ec (=1004: 4-byte PN + 1000 payload).
    i1 = "<b 0xc3000000010800><r 8><b 0x000043ec><r 4><r 1000>"
    return {"jc": 4, "jmin": 40, "jmax": 70, "s1": s1, "s2": s2,
            "h1": h1, "h2": h2, "h3": h3, "h4": h4, "i1": i1}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--force", action="store_true", help="overwrite existing secrets (all clients must be re-enrolled)")
    args = ap.parse_args()
    if OUT.exists() and not args.force:
        print(f"{OUT} exists; nothing done (use --force to regenerate)")
        return 0
    devices = [d["name"] for d in yaml.safe_load(VARS.read_text())["vpn_devices"]]

    reality_priv, reality_pub = reality_pair()
    eu_awg_priv, eu_awg_pub = wg_pair()
    msk_awg_priv, msk_awg_pub = wg_pair()
    eu_link_priv, eu_link_pub = wg_pair()
    ctl_priv, ctl_pub = wg_pair()

    data = {
        "reality_private_key": reality_priv,
        "reality_public_key": reality_pub,
        "xhttp_path": secrets.token_urlsafe(12),
        "sub_token": secrets.token_urlsafe(24),
        "awg_eu": {"private_key": eu_awg_priv, "public_key": eu_awg_pub, **awg_params()},
        "awg_msk": {"private_key": msk_awg_priv, "public_key": msk_awg_pub, **awg_params()},
        "msk_link": {"private_key": eu_link_priv, "public_key": eu_link_pub, "psk": wg_psk()},
        "awg_control": {"private_key": ctl_priv, "public_key": ctl_pub},
        "device_secrets": {},
    }
    for name in devices:
        eu_priv, eu_pub = wg_pair()
        msk_priv, msk_pub = wg_pair()
        data["device_secrets"][name] = {
            "uuid_home": str(uuid.uuid4()),
            "uuid_abroad": str(uuid.uuid4()),
            "reality_short_id": secrets.token_hex(8),
            "awg_eu": {"private_key": eu_priv, "public_key": eu_pub, "psk": wg_psk()},
            "awg_msk": {"private_key": msk_priv, "public_key": msk_pub, "psk": wg_psk()},
        }
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("# GENERATED by scripts/init-secrets.py. Never commit. Back it up somewhere safe.\n"
                   + yaml.safe_dump(data, sort_keys=False))
    os.chmod(OUT, 0o600)
    print(f"wrote {OUT} for devices: {', '.join(devices)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
